#' Diagnose Summation Errors
#'
#' Utility functions to analyze summation check failures by extracting and organizing
#' the underlying REMIND and PIAM data for each failed equation.
#'
#' @param mifs Path to MIF files or quitte object containing REMIND output
#' @param mapping Path to mapping file or mapping data frame
#' @param summationFile Path to summation file defining parent-child relationships
#' @param errorLog Data frame or path to error log with columns: model, scenario, region, period, variable
#'        If generatePIAM=TRUE and errorLog not provided, uses checkSummations output
#' @param generatePIAM Logical (default TRUE) or path to PIAM export file.
#'        If TRUE, runs generateIIASASubmission to create PIAM data.
#'        If FALSE or path string, uses existing PIAM export.
#' @param timesteps Vector of periods to include (default: all)
#'
#' @return List with one element per failed equation. Each element contains:
#'   - parent: Parent variable name
#'   - children: Vector of child variable names
#'   - piam_factors: Named numeric vector of factors (names = child variables, default 1)
#'   - remind_data: Data frame with columns: model, scenario, region, period, variable, unit, value
#'   - piam_data: Data frame with columns: model, scenario, region, period, variable, unit, value
#'   - error_instances: Data frame with actual error rows from errorLog
#'
#' @keywords internal
#' @export
diagnoseSummationErrors <- function(mifs, mapping, summationFile, errorLog = NULL, generatePIAM = TRUE, timesteps = NULL) {

  # Generate or load PIAM export file
  if (isTRUE(generatePIAM)) {
    message("# Generating PIAM export with generateIIASASubmission...")
    # Use current directory to avoid temp cleanup
    output_dir <- "."
    export_filename <- "diagnostic_piam_export.mif"
    error_log_filename <- "diagnostic_piam_checkSummations.csv"

    generateIIASASubmission(mifs = mifs, mapping = mapping,
                           outputDirectory = output_dir, outputFilename = export_filename,
                           checkSummation = TRUE, logFile = error_log_filename)
    piam_export_file <- file.path(output_dir, export_filename)

    # Also look for error log generated by checkSummations
    if (is.null(errorLog)) {
      error_log_file <- file.path(output_dir, error_log_filename)
      if (file.exists(error_log_file)) {
        errorLog <- read.csv(error_log_file, sep = ";", stringsAsFactors = FALSE)
        message(sprintf("  Using error log from generateIIASASubmission (%d rows)", nrow(errorLog)))
      }
    }

    message("  PIAM export saved to: ", piam_export_file)
    message("  Remember this file for later iterations without regeneration")
  } else if (is.character(generatePIAM)) {
    message("# Using provided PIAM export file...")
    piam_export_file <- generatePIAM
  } else {
    stop("generatePIAM must be TRUE, FALSE, or a path to a PIAM export file")
  }

  # Load error log if needed
  if (is.character(errorLog)) {
    message("# Loading error log...")
    errorLog <- read.csv(errorLog, sep = ";", stringsAsFactors = FALSE)
  }

  # Load mapping
  message("# Loading mapping...")
  if (is.character(mapping)) {
    mapData <- getMapping(mapping) %>%
      filter(!.data$piam_variable %in% "", !is.na(.data$piam_variable)) %>%
      mutate(
        "piam_variable" = removePlus(.data$piam_variable),
        "piam_factor" = ifelse(is.na(.data$piam_factor), 1, as.numeric(.data$piam_factor))
      )
  } else {
    mapData <- mapping %>%
      mutate(
        "piam_variable" = removePlus(.data$piam_variable)
      )
  }

  # Load summation file
  message("# Loading summation file...")
  if (is.character(summationFile)) {
    summations <- read.csv(summationFile, sep = ";", stringsAsFactors = FALSE)
  } else {
    summations <- summationFile
  }

  # Load REMIND data directly from MIF (once, for efficiency)
  message("# Loading REMIND data from MIF...")
  message("  Reading MIF file...")
  remind_all <- deletePlus(readMifs(mifs))
  if (!is.null(timesteps)) {
    remind_all <- remind_all %>% filter(.data$period %in% timesteps)
  }
  message("  ✓ REMIND data loaded")

  # Load PIAM data from export file (once, for efficiency)
  message("# Loading PIAM data from export...")
  if (is.character(piam_export_file)) {
    # Try different file formats
    if (grepl("\\.xlsx?$", piam_export_file)) {
      piam_all <- read.quitte(piam_export_file)
    } else if (grepl("\\.csv$", piam_export_file)) {
      piam_all <- read.quitte(piam_export_file)
    } else if (grepl("\\.mif$", piam_export_file)) {
      message("  Reading PIAM MIF file...")
      piam_all <- deletePlus(readMifs(piam_export_file))
    } else {
      stop("Unsupported PIAM export file format: ", piam_export_file)
    }
    if (!is.null(timesteps)) {
      piam_all <- piam_all %>% filter(.data$period %in% timesteps)
    }
  } else {
    stop("piam_export_file must be a path to a PIAM export file")
  }
  message("  ✓ PIAM data loaded")

  # Handle missing or invalid error log
  if (is.null(errorLog) || nrow(errorLog) == 0) {
    message("# No error log provided or error log is empty")
    message("# Diagnostic requires an error log with failed equations to diagnose")
    return(list())
  }

  unique_errors <- errorLog %>%
    distinct(.data$scenario, .data$region, .data$period, .data$variable) %>%
    mutate("parent" = .data$variable) %>%
    select(-"variable")

  if (nrow(unique_errors) == 0) {
    message("# No failed equations found in filtered data")
    return(list())
  }

  message(sprintf("# Found %d unique failed equations", nrow(unique_errors)))

  # Build diagnostics list
  diagnostics_list <- list()
  counter <- 1

  for (i in seq_len(nrow(unique_errors))) {
    parent_var <- unique_errors$parent[i]

    child_vars <- getPiamChildrenForEquation(parent_var, summations)

    if (length(child_vars) == 0) {
      warning(sprintf("No summation rule found for parent: %s", parent_var))
      next
    }

    # Extract clean parent name for reference (without the number suffix)
    parent_var_clean <- getParentVariable(parent_var)

    # Get factors for each child variable
    summation_rules <- summations %>%
      filter(.data$parent == parent_var &
             !is.na(.data$child) & .data$child != "")

    factors <- setNames(
      as.numeric(summation_rules$factor),
      summation_rules$child
    )

    # Get actual REMIND variable values using dedicated extraction function
    remind_subset <- extractRemindValues(
      remind_all,
      mapData,
      parent_var_clean,
      scenario = unique_errors$scenario[i],
      region = unique_errors$region[i],
      period = unique_errors$period[i]
    )

    # Get REMIND variables that are expected for this parent
    remind_vars_for_parent <- mapData %>%
      filter(.data$variable == parent_var_clean) %>%
      distinct(.data$piam_variable, .data$piam_factor)

    # Add missing REMIND variables with NA values
    missing_remind_vars <- remind_vars_for_parent %>%
      filter(!(.data$piam_variable %in% remind_subset$piam_variable))

    if (nrow(missing_remind_vars) > 0) {
      # Get model/scenario/region/period info from any existing row or from error
      if (nrow(remind_subset) > 0) {
        model_val <- remind_subset$model[1]
      } else {
        model_val <- "Unknown"
      }

      missing_rows <- missing_remind_vars %>%
        mutate(
          model = model_val,
          scenario = unique_errors$scenario[i],
          region = unique_errors$region[i],
          period = unique_errors$period[i],
          piam_unit = NA_character_,
          value = NA_real_
        ) %>%
        select("model", "scenario", "region", "period", "piam_variable", "piam_unit", "value", "piam_factor")
      remind_subset <- bind_rows(remind_subset, missing_rows)
    }

    # Get actual PIAM child variable values from already-loaded data
    piam_subset <- piam_all %>%
      filter(
        .data$variable %in% child_vars,
        .data$scenario == unique_errors$scenario[i],
        .data$region == unique_errors$region[i],
        .data$period == unique_errors$period[i]
      ) %>%
      select("model", "scenario", "region", "period", "variable", "unit", "value") %>%
      distinct()

    # Add rows for missing child variables with NA values
    missing_children <- setdiff(child_vars, piam_subset$variable)
    if (length(missing_children) > 0) {
      # Get model/unit info from any existing row to maintain consistency
      model_val <- if (nrow(piam_subset) > 0) piam_subset$model[1] else "Unknown"

      missing_rows <- data.frame(
        model = model_val,
        scenario = unique_errors$scenario[i],
        region = unique_errors$region[i],
        period = unique_errors$period[i],
        variable = missing_children,
        unit = NA_character_,
        value = NA_real_,
        stringsAsFactors = FALSE
      )
      piam_subset <- bind_rows(piam_subset, missing_rows)
    }

    piam_subset <- piam_subset %>%
      arrange(desc(.data$value))

    error_instances <- errorLog %>%
      filter(
        .data$scenario == unique_errors$scenario[i] &
        .data$region == unique_errors$region[i] &
        .data$period == unique_errors$period[i] &
        .data$variable == parent_var
      )

    # Store in list
    diagnostics_list[[counter]] <- list(
      parent = parent_var_clean,
      children = child_vars,
      piam_factors = factors,
      remind_data = as.data.frame(remind_subset),
      piam_data = as.data.frame(piam_subset),
      error_instances = as.data.frame(error_instances)
    )

    counter <- counter + 1
  }

  names(diagnostics_list) <- seq_len(length(diagnostics_list))

  message(sprintf("# Created %d diagnostic elements", length(diagnostics_list)))
  return(diagnostics_list)
}


#' Calculate Summation Totals
#'
#' Auxiliary function to compute sums of both sides (REMIND and PIAM) of a summation check.
#' Useful for validation and debugging.
#'
#' @param diagnostics_element Single element from diagnoseSummationErrors output
#' @param by_variables If TRUE, return sums broken down by variable. If FALSE, return overall totals.
#'
#' @return Data frame with columns:
#'   - model, scenario, region, period (if by_variables = FALSE, these identify the check)
#'   - side: "REMIND" or "PIAM"
#'   - variable: (if by_variables = TRUE) the variable name
#'   - total: Sum of values
#'
#' @keywords internal
#' @export
getSummationTotals <- function(diagnostics_element, by_variables = TRUE) {

  parent <- diagnostics_element$parent
  children <- diagnostics_element$children
  factors <- diagnostics_element$piam_factors
  remind_data <- diagnostics_element$remind_data
  piam_data <- diagnostics_element$piam_data

  # REMIND side: sum of child variables with their factors
  remind_totals <- remind_data %>%
    mutate(
      "adjusted_value" = .data$value * .data$piam_factor,
      "side" = "REMIND"
    )

  if (by_variables) {
    remind_totals <- remind_totals %>%
      select("model", "scenario", "region", "period", "side", "variable" = "piam_variable", "total" = "adjusted_value")
  } else {
    remind_totals <- remind_totals %>%
      group_by(.data$model, .data$scenario, .data$region, .data$period, .data$side) %>%
      summarise("total" = sum(.data$adjusted_value, na.rm = TRUE), .groups = "drop") %>%
      mutate("variable" = parent)
  }

  # PIAM side: parent and children values
  piam_totals <- piam_data %>%
    mutate("side" = "PIAM") %>%
    select("model", "scenario", "region", "period", "side", "variable", "total" = "value")

  # Combine
  result <- bind_rows(remind_totals, piam_totals) %>%
    arrange(.data$model, .data$scenario, .data$region, .data$period, .data$side, .data$variable)

  return(result)
}


#' Display Summation Diagnostic
#'
#' Pretty-print a summation error diagnosis for inspection
#'
#' @param diagnostics_element Single element from diagnoseSummationErrors output
#'
#' @keywords internal
#' @export
printSummationDiagnostic <- function(diagnostics_element) {

  parent <- diagnostics_element$parent
  children <- diagnostics_element$children
  factors <- diagnostics_element$piam_factors
  error_inst <- diagnostics_element$error_instances

  cat("\n")
  cat(strrep("=", 80), "\n")
  cat("Parent Variable:", parent, "\n")
  cat("Child Variables:", paste(children, collapse = ", "), "\n")
  cat("Factors:", paste(names(factors), "=", format(factors, trim = TRUE), collapse = "; "), "\n")
  cat("Failed Instances:", nrow(error_inst), "\n")
  cat(strrep("=", 80), "\n")

  totals <- getSummationTotals(diagnostics_element, by_variables = FALSE)
  cat("\nAggregated Totals:\n")
  print(totals)

  cat("\n")
}


#' Analyze Missing Components in Summation Errors
#'
#' For each failed equation, identify which child variables are missing or have zero values
#'
#' @param diagnostics_list List from diagnoseSummationErrors output
#'
#' @return Data frame with columns:
#'   - equation_id: Index in diagnostics_list
#'   - parent: Parent variable name
#'   - missing_children: Comma-separated list of children with NA values
#'   - zero_children: Comma-separated list of children with zero values
#'   - present_children: Comma-separated list of children with actual values
#'
#' @keywords internal
#' @export
analyzeMissingComponents <- function(diagnostics_list) {

  results <- list()

  for (i in seq_along(diagnostics_list)) {
    diag <- diagnostics_list[[i]]

    piam_data <- diag$piam_data
    parent <- diag$parent
    children <- diag$children

    # Check which children are present in piam_data
    child_status <- tibble(
      "child" = children,
      "in_data" = .data$child %in% piam_data$variable,
      "has_value" = FALSE
    )

    # For children that are in data, check if they have non-zero values
    for (j in seq_len(nrow(child_status))) {
      child_var <- child_status$child[j]
      child_data <- piam_data %>% filter(.data$variable == child_var)

      if (nrow(child_data) > 0) {
        # Check if any non-NA, non-zero values exist
        has_value <- any(!is.na(child_data$value) & child_data$value != 0)
        child_status$has_value[j] <- has_value
      }
    }

    missing <- child_status %>% filter(!.data$in_data) %>% pull("child")
    zero <- child_status %>% filter(.data$in_data & !.data$has_value) %>% pull("child")
    present <- child_status %>% filter(.data$in_data & .data$has_value) %>% pull("child")

    results[[i]] <- tibble(
      "equation_id" = i,
      "parent" = parent,
      "missing_children" = paste(missing, collapse = "; "),
      "zero_children" = paste(zero, collapse = "; "),
      "present_children" = paste(present, collapse = "; "),
      "n_missing" = length(missing),
      "n_zero" = length(zero),
      "n_present" = length(present)
    )
  }

  bind_rows(results)
}


#' Summarize Summation Errors
#'
#' Create a summary of error types and patterns across all failed equations
#'
#' @param diagnostics_list List from diagnoseSummationErrors output
#'
#' @return List containing:
#'   - by_parent: Count of failures per parent variable
#'   - by_missing_components: Distribution of how many children are missing
#'   - component_analysis: Detailed analysis from analyzeMissingComponents
#'
#' @keywords internal
#' @export
summarizeSummationErrors <- function(diagnostics_list) {

  # Count by parent
  parents <- sapply(diagnostics_list, function(x) x$parent)
  by_parent <- tibble(
    "parent" = names(table(parents)),
    "n_failures" = as.numeric(table(parents))
  ) %>% arrange(desc(.data$n_failures))

  # Get component analysis
  component_analysis <- analyzeMissingComponents(diagnostics_list)

  # Summarize patterns
  by_pattern <- component_analysis %>%
    group_by(.data$n_missing, .data$n_zero, .data$n_present) %>%
    summarise("count" = n(), .groups = "drop") %>%
    arrange(desc(.data$count))

  list(
    by_parent = by_parent,
    by_missing_pattern = by_pattern,
    component_analysis = component_analysis,
    total_failed_equations = length(diagnostics_list)
  )
}


#' Extract PIAM Factors from Mapping
#'
#' Helper to get piam_factors in a named format (default 1) for specified variables
#'
#' @param mapping Data frame or path to mapping file
#' @param piam_variables Vector of PIAM variable names to extract factors for
#'
#' @return Named numeric vector where names are piam_variables and values are factors
#'
#' @keywords internal
#' @export
extractPiamFactors <- function(mapping, piam_variables) {

  if (is.character(mapping)) {
    mapping <- read.csv(mapping, sep = ";", stringsAsFactors = FALSE)
  }

  # Create a mapping from piam_variable to piam_factor
  factor_map <- mapping %>%
    select("piam_variable", "piam_factor") %>%
    distinct() %>%
    mutate(
      "piam_factor" = ifelse(is.na(.data$piam_factor), 1, as.numeric(.data$piam_factor))
    ) %>%
    filter(.data$piam_variable %in% piam_variables)

  # Return as named vector
  factors <- setNames(
    factor_map$piam_factor,
    factor_map$piam_variable
  )

  # Ensure all requested variables are present (default 1 if not in mapping)
  for (var in piam_variables) {
    if (!(var %in% names(factors))) {
      factors[[var]] <- 1
    }
  }

  return(factors)
}
